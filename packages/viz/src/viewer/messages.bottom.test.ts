test("with messages, every path keeps LABEL_PAD clear of the canvas bottom", () => {
  expect(messagesOf(machine).length).toBeGreaterThan(0);
  const placed = placeMachine(machine);
  const ys = [...placed.messages, ...placed.edges].flatMap((line) => line.points.map((p) => p.y));
  expect(Math.max(...ys)).toBeLessThanOrEqual(placed.height - LABEL_PAD);
  expect(overlapsOf(placed)).toEqual([]);
});
